#!/usr/bin/env python3
"""
gen_research_bonus_tracking.py - script-side ledger of research bonuses, for the [research-rush]
ai_will_do gate. Owns two families of generated lines, both delimited by marker comments.

WHY. `has_tech_bonus` cannot express "a bonus is available for this tech" (console harness
WA_TEST_research_bonus, 6 runs, 2026-09-08: the `technology =` form never depends on the tech,
the `category =` form stays true on spent records, which the engine never deletes). So WA keeps
its own counters on the country:

    WA_rb_uses_<category>     uses granted by ANY bonus of that category, not yet consumed
    WA_rb_ahead2_<category>   the subset granted by a bonus with ahead_reduction >= 2
    WA_rb_uses_t_<tech>       same two families keyed by technology for `technology = X` bonuses
    WA_rb_ahead2_t_<tech>

1. GRANT - after every `add_tech_bonus = { ... }` block under common/ and events/, one
   `add_to_variable` per target key (category or technology), in the same scope as the grant.
   `uses` defaults to 1. A block listing several technologies shares its uses across them
   (each key gets max(1, uses // n)).
2. CONSUME - in every technology of common/technologies/, inside its `on_research_complete = { }`
   (created when absent, appended when present): an if / else_if chain that decrements the FIRST
   key with uses left - the tech's own key first, then its categories in file order - and clamps
   the ahead2 twin at 0. Residual, by construction: the engine claims a bonus when a research
   STARTS; script sees completion, so a tech of the category already running at grant time
   completes first and decrements in the bonus's place. The gate then closes early, never late.

The ai_will_do gate that READS these counters is emitted by tools/migrations/ai_will_do/ (generator)
and migrated by add_research_bonus_exemption.py; it is not this tool's business.

Idempotent: managed regions are rewritten from scratch every run; bytes outside them are untouched
(BOM, CRLF, indentation). Refuses (exit 2) on an add_tech_bonus block it cannot parse.

Usage (any cwd; the mod root is derived from this file's location):
  python gen_research_bonus_tracking.py --dry-run     # per-file counts + unified diff summary
  python gen_research_bonus_tracking.py               # write
  python gen_research_bonus_tracking.py --check       # exit 1 if any file is out of date
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TECH_DIR = REPO / "common" / "technologies"
GRANT_DIRS = [REPO / "common", REPO / "events"]

TOOL = "tools/gen/gen_research_bonus_tracking.py"
G_BEGIN = f"# WA_RB_GRANT begin - generated by {TOOL}, do not edit"
G_END = "# WA_RB_GRANT end"
C_BEGIN = f"# WA_RB_CONSUME begin - generated by {TOOL}, do not edit"
C_END = "# WA_RB_CONSUME end"

RE_G_BEGIN = re.compile(r"^\s*# WA_RB_GRANT begin\b")
RE_G_END = re.compile(r"^\s*# WA_RB_GRANT end\b")
RE_C_BEGIN = re.compile(r"^\s*# WA_RB_CONSUME begin\b")
RE_C_END = re.compile(r"^\s*# WA_RB_CONSUME end\b")
RE_ATB_OPEN = re.compile(r"^(\s*)add_tech_bonus\s*=\s*\{(.*)$")
RE_HEADER = re.compile(r"^(\s*)([A-Za-z0-9_]+)\s*=\s*\{")
RE_CATEGORIES_OPEN = re.compile(r"^\s*categories\s*=\s*\{(.*)$")
RE_ORC_OPEN = re.compile(r"^(\s*)on_research_complete\s*=\s*\{\s*$")


def _nl(line: str) -> str:
    return line[len(line.rstrip("\r\n")):] or "\n"


def _code(line: str) -> str:
    return line.split("#", 1)[0]


# ------------------------------------------------------------------------------------ grants

def _strip_managed(lines, re_begin, re_end):
    out, skipping = [], False
    for line in lines:
        if not skipping and re_begin.match(line):
            skipping = True
            continue
        if skipping:
            if re_end.match(line):
                skipping = False
            continue
        out.append(line)
    return out


def _parse_bonus(body: str):
    """body = text between the braces of one add_tech_bonus block. Returns (cats, techs, uses, ahead)."""
    cats = re.findall(r"\bcategory\s*=\s*([A-Za-z0-9_]+)", body)
    techs = re.findall(r"\btechnology\s*=\s*([A-Za-z0-9_]+)", body)
    um = re.search(r"\buses\s*=\s*(\d+)", body)
    uses = int(um.group(1)) if um else 1
    am = re.search(r"\bahead_reduction\s*=\s*([\d.]+)", body)
    ahead = float(am.group(1)) if am else 0.0
    return cats, techs, uses, ahead


def grant_lines(ind: str, nl: str, cats, techs, uses: int, ahead: float):
    per_tech = max(1, uses // len(techs)) if techs else uses
    out = [f"{ind}{G_BEGIN}{nl}"]
    for c in cats:
        out.append(f"{ind}add_to_variable = {{ WA_rb_uses_{c} = {uses} }}{nl}")
        if ahead >= 2:
            out.append(f"{ind}add_to_variable = {{ WA_rb_ahead2_{c} = {uses} }}{nl}")
    for t in techs:
        out.append(f"{ind}add_to_variable = {{ WA_rb_uses_t_{t} = {per_tech} }}{nl}")
        if ahead >= 2:
            out.append(f"{ind}add_to_variable = {{ WA_rb_ahead2_t_{t} = {per_tech} }}{nl}")
    out.append(f"{ind}{G_END}{nl}")
    return out


def process_grants(data: bytes, path: Path):
    text = data.decode("utf-8")
    lines = _strip_managed(text.splitlines(keepends=True), RE_G_BEGIN, RE_G_END)
    out = []
    count = 0
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        m = RE_ATB_OPEN.match(_code(line))
        if not m:
            out.append(line)
            i += 1
            continue
        ind = m.group(1)
        # collect the block: from this line to the line holding its closing brace (no nesting inside)
        body = m.group(2)
        j = i
        depth = 1 + _code(line).count("{") - 1 - _code(line).count("}")
        out.append(line)
        while depth > 0:
            j += 1
            if j >= n:
                sys.exit(f"{path}: unterminated add_tech_bonus block at line {i + 1}")
            c = _code(lines[j])
            if "{" in c:
                sys.exit(f"{path}: nested brace inside add_tech_bonus at line {j + 1} - not supported")
            depth -= c.count("}")
            body += "\n" + c
            out.append(lines[j])
        cats, techs, uses, ahead = _parse_bonus(body)
        if not cats and not techs:
            # an inert grant (vanilla-inherited: events/AAT_Norway.txt) - nothing to track
            print(f"  WARNING {path.relative_to(REPO)}:{i + 1}: add_tech_bonus names no category and no technology - skipped")
        else:
            out += grant_lines(ind, _nl(lines[j]), cats, techs, uses, ahead)
            count += 1
        i = j + 1
    return "".join(out).encode("utf-8"), count


# ---------------------------------------------------------------------------------- consume

def _tech_categories(lines):
    """{tech: [categories]} for every depth-1 tech, comments stripped."""
    cats = {}
    depth = 0
    tech = None
    in_cats = False
    for line in lines:
        code = _code(line)
        if in_cats:
            cats[tech] += re.findall(r"[A-Za-z0-9_]+", code.split("}", 1)[0])
            if "}" in code:
                in_cats = False
        else:
            m = RE_HEADER.match(code)
            if m and depth == 1:
                tech = m.group(2)
                cats.setdefault(tech, [])
            cm = RE_CATEGORIES_OPEN.match(code)
            if cm and depth == 2 and tech:
                rest = cm.group(1)
                cats[tech] += re.findall(r"[A-Za-z0-9_]+", rest.split("}", 1)[0])
                in_cats = "}" not in rest
        depth += code.count("{") - code.count("}")
    return cats


def consume_lines(ind: str, nl: str, tech: str, cats):
    """The if / else_if chain, one line per key. `ind` = indent inside on_research_complete."""
    out = [f"{ind}{C_BEGIN}{nl}"]
    keys = [f"t_{tech}"] + list(cats)
    for k, key in enumerate(keys):
        kw = "if" if k == 0 else "else_if"
        u, a = f"WA_rb_uses_{key}", f"WA_rb_ahead2_{key}"
        out.append(f"{ind}{kw} = {{ limit = {{ check_variable = {{ {u} > 0 }} }} "
                   f"subtract_from_variable = {{ {u} = 1 }} "
                   f"if = {{ limit = {{ check_variable = {{ {u} < 1 }} }} clear_variable = {u} }} "
                   f"if = {{ limit = {{ check_variable = {{ {a} > 0 }} }} subtract_from_variable = {{ {a} = 1 }} "
                   f"if = {{ limit = {{ check_variable = {{ {a} < 1 }} }} clear_variable = {a} }} }} }}{nl}")
    out.append(f"{ind}{C_END}{nl}")
    return out


def process_consume(data: bytes, path: Path):
    text = data.decode("utf-8")
    lines = _strip_managed(text.splitlines(keepends=True), RE_C_BEGIN, RE_C_END)
    # drop on_research_complete blocks that the strip left EMPTY (tool-created ones)
    cleaned = []
    i = 0
    while i < len(lines):
        m = RE_ORC_OPEN.match(_code(lines[i]))
        if m and i + 1 < len(lines) and re.match(r"^\s*\}\s*$", _code(lines[i + 1])):
            i += 2
            continue
        cleaned.append(lines[i])
        i += 1
    lines = cleaned
    cats = _tech_categories(lines)
    out = []
    count = 0
    depth = 0
    tech = None
    tech_ind = ""
    orc_seen = False
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        code = _code(line)
        m = RE_HEADER.match(code)
        if m and depth == 1:
            tech = m.group(2)
            tech_ind = m.group(1)
            orc_seen = False
        om = RE_ORC_OPEN.match(code) if (depth == 2 and tech) else None
        new_depth = depth + code.count("{") - code.count("}")
        if om:
            out.append(line)
            out += consume_lines(om.group(1) + "\t", _nl(line), tech, cats.get(tech, []))
            orc_seen = True
            count += 1
        elif depth == 2 and new_depth == 1 and tech and not orc_seen and re.match(r"^\s*\}\s*$", code):
            # closing brace of the tech: create the block just before it
            nl = _nl(line)
            ind = tech_ind + "\t"
            out.append(f"{ind}on_research_complete = {{{nl}")
            out += consume_lines(ind + "\t", nl, tech, cats.get(tech, []))
            out.append(f"{ind}}}{nl}")
            out.append(line)
            count += 1
            tech = None
        else:
            out.append(line)
        depth = new_depth
        i += 1
    return "".join(out).encode("utf-8"), count


# ------------------------------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()

    changed = []
    grants = consumes = 0
    seen = set()
    for d in GRANT_DIRS:
        for path in sorted(d.rglob("*.txt")):
            if path in seen:
                continue
            seen.add(path)
            data = path.read_bytes()
            if b"add_tech_bonus" not in data and b"WA_RB_GRANT" not in data:
                continue
            new, count = process_grants(data, path)
            grants += count
            if new != data:
                changed.append((path, new, f"{count} grant(s)"))
    for path in sorted(TECH_DIR.glob("*.txt")):
        data = path.read_bytes()
        new, count = process_consume(data, path)
        consumes += count
        if new != data:
            changed.append((path, new, f"{count} consume block(s)"))

    for path, new, what in changed:
        print(f"  {path.relative_to(REPO)}: {what}")
        if not args.dry_run and not args.check:
            assert new.startswith(b"\xef\xbb\xbf") == path.read_bytes().startswith(b"\xef\xbb\xbf")
            path.write_bytes(new)
    verb = "written" if not (args.dry_run or args.check) else "out of date"
    print(f"{len(changed)} file(s) {verb}; {grants} add_tech_bonus block(s) tracked, {consumes} technologies with a consume block")
    if args.check and changed:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
