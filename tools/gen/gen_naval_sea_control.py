#!/usr/bin/env python3
"""
gen_naval_sea_control.py - generate the sea-control data of the naval posture system.

[naval-invasion-discipline] N3 part B. The engine answers "does an enemy (or my side) hold naval
control of sea region R" (`has_enemy_naval_control = R` / `has_naval_control = R`, install
documentation/triggers_documentation.md) but has no iterator over sea regions and no link from a
sea region to the land states on its shore. This tool derives that link from the map and writes
it as literal-id script, so every consequence of losing a sea is applied REGION by REGION.

Sources (never edited by this tool):
  map/strategicregions/*.txt   sea regions = the files carrying `naval_terrain`
  map/definition.csv           province id <-> colour, province type (land / sea / lake)
  map/provinces.bmp            pixel adjacency (a sea province touching a land province)
  history/states/*.txt         province -> state

Outputs (all GENERATED - never hand-edit; header line says so):
  common/scripted_effects/WA_AI_NAVAL_sea_control_generated.txt
      WA_AI_NAVAL_update_sea_control_country  (THIS = an AI major at war, monthly sweep)
          per sea region the enemy controls: timed country flag WA_AI_NAVAL_lost_sea_<R>;
          temp _nsc_lost (count) and _nsc_home_lost (1 if the region borders a state THIS holds)
      WA_AI_NAVAL_update_sea_control_states   (any scope, once per monthly sweep)
          per coastal state whose controller (at war) holds naval control of an adjacent sea
          region: timed state flag WA_AI_NAVAL_controller_holds_sea
  common/scripted_triggers/WA_AI_NAVAL_sea_control_generated.txt
      WA_AI_NAVAL_should_avoid_lost_sea_<R> - posture inferior AND the region is lost
  common/ai_strategy/WA_AI_NAVAL_DEFAULT_sea_control_generated.txt
      one block per sea region: naval_avoid_region <R> +500 behind the trigger above

Usage (any cwd; the mod root is derived from this file's location):
  python tools/gen/gen_naval_sea_control.py --dry-run   # report, write nothing
  python tools/gen/gen_naval_sea_control.py --check     # exit 1 if the files on disk drifted
  python tools/gen/gen_naval_sea_control.py             # write the three files
The bmp scan takes about a minute without numpy, a few seconds with it.
"""

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

from core import parse_definition_full, read_file_with_bom  # noqa: E402

MAP = REPO / "map"
STATES = REPO / "history" / "states"
OUT_EFFECTS = REPO / "common" / "scripted_effects" / "WA_AI_NAVAL_sea_control_generated.txt"
OUT_TRIGGERS = REPO / "common" / "scripted_triggers" / "WA_AI_NAVAL_sea_control_generated.txt"
OUT_STRATEGY = REPO / "common" / "ai_strategy" / "WA_AI_NAVAL_DEFAULT_sea_control_generated.txt"

POSTURE_EFFECTS = REPO / "common" / "scripted_effects" / "WA_AI_NAVAL_posture_effects.txt"
RE_FLAG_DAYS = re.compile(r"^@WA_AI_NAVAL_SEA_FLAG_DAYS\s*=\s*(\d+)", re.M)
AVOID_VALUE = 500       # naval_avoid_region: between a soft nudge (100-200) and a soft wall (1000)
GEN_LINE = "# GENERATED by tools/gen/gen_naval_sea_control.py - never hand-edit; regenerate instead."

RE_ID = re.compile(r"^\s*id\s*=\s*(\d+)", re.M)
RE_PROVS = re.compile(r"provinces\s*=\s*\{([^}]*)\}", re.S)
RE_NAVAL = re.compile(r"^\s*naval_terrain\s*=", re.M)


def sea_regions():
    """Return {region_id: set(sea province ids)} for every strategic region with naval_terrain."""
    out = {}
    for f in sorted((MAP / "strategicregions").glob("*.txt")):
        text, _ = read_file_with_bom(f)
        if not RE_NAVAL.search(text):
            continue
        m_id, m_pr = RE_ID.search(text), RE_PROVS.search(text)
        if not (m_id and m_pr):
            continue
        out[int(m_id.group(1))] = {int(p) for p in re.findall(r"\d+", m_pr.group(1))}
    return out


def province_states():
    """Return {province id: state id} from history/states."""
    out = {}
    for f in STATES.glob("*.txt"):
        text, _ = read_file_with_bom(f)
        m_id, m_pr = RE_ID.search(text), RE_PROVS.search(text)
        if not (m_id and m_pr):
            continue
        sid = int(m_id.group(1))
        for p in re.findall(r"\d+", m_pr.group(1)):
            out[int(p)] = sid
    return out


def adjacency_pairs(rgb_to_province):
    """Return the set of unordered (province, province) pairs that touch on provinces.bmp."""
    from PIL import Image
    img = Image.open(MAP / "provinces.bmp").convert("RGB")
    try:
        import numpy as np
    except ImportError:
        np = None
    pairs = set()
    if np is not None:
        a = np.asarray(img, dtype=np.uint32)
        key = (a[:, :, 0] << 16) | (a[:, :, 1] << 8) | a[:, :, 2]
        lut = {(r << 16) | (g << 8) | b: pid for (r, g, b), pid in rgb_to_province.items()}
        for x, y in ((key[:, :-1], key[:, 1:]), (key[:-1, :], key[1:, :])):
            diff = x != y
            for k1, k2 in set(zip(x[diff].tolist(), y[diff].tolist())):
                p1, p2 = lut.get(k1), lut.get(k2)
                if p1 is not None and p2 is not None:
                    pairs.add((min(p1, p2), max(p1, p2)))
        return pairs
    px, (w, h) = img.load(), img.size
    for yy in range(h):
        for xx in range(w):
            c = px[xx, yy]
            for nx, ny in ((xx + 1, yy), (xx, yy + 1)):
                if nx < w and ny < h:
                    d = px[nx, ny]
                    if d != c:
                        p1, p2 = rgb_to_province.get(c), rgb_to_province.get(d)
                        if p1 is not None and p2 is not None:
                            pairs.add((min(p1, p2), max(p1, p2)))
    return pairs


def flag_days():
    """The generated flags share their lifetime with the sweep's own flags: one number, read here."""
    m = RE_FLAG_DAYS.search(read_file_with_bom(POSTURE_EFFECTS)[0])
    if not m:
        sys.exit(f"@WA_AI_NAVAL_SEA_FLAG_DAYS not found in {POSTURE_EFFECTS.relative_to(REPO)}")
    return int(m.group(1))


def build():
    rgb_to_province, ptype = parse_definition_full(MAP / "definition.csv")
    regions = sea_regions()
    sea_to_region = {p: r for r, ps in regions.items() for p in ps}
    prov_state = province_states()
    shore = defaultdict(set)  # region -> coastal states
    for p1, p2 in adjacency_pairs(rgb_to_province):
        for sea, land in ((p1, p2), (p2, p1)):
            if ptype.get(sea) == "sea" and ptype.get(land) == "land":
                r, s = sea_to_region.get(sea), prov_state.get(land)
                if r is not None and s is not None:
                    shore[r].add(s)
    return {r: sorted(shore[r]) for r in sorted(regions) if shore.get(r)}, len(regions)


def render(shore):
    FLAG_DAYS = flag_days()
    eff, trg, strat = [GEN_LINE], [GEN_LINE], [GEN_LINE]
    eff += [
        "# [naval-invasion-discipline] N3 part B - sea control, region by region.",
        "# Spec: documentation/WA_AI_MILITARY_SYSTEM.md section 27. Caller: WA_AI_NAVAL_posture_sweep.",
        "",
        "# THIS = an AI major at war. OUT: flags WA_AI_NAVAL_lost_sea_<R>, temps _nsc_lost / _nsc_home_lost.",
        "WA_AI_NAVAL_update_sea_control_country = {",
        "\tset_temp_variable = { _nsc_lost = 0 }",
        "\tset_temp_variable = { _nsc_home_lost = 0 }",
    ]
    for r, states in shore.items():
        held = " ".join(f"{s} = {{ is_controlled_by = PREV }}" for s in states)
        eff += [
            f"\tif = {{ limit = {{ has_enemy_naval_control = {r} }}",
            f"\t\tset_country_flag = {{ flag = WA_AI_NAVAL_lost_sea_{r} value = 1 days = {FLAG_DAYS} }}",
            "\t\tadd_to_temp_variable = { _nsc_lost = 1 }",
            f"\t\tif = {{ limit = {{ OR = {{ {held} }} }} set_temp_variable = {{ _nsc_home_lost = 1 }} }}",
            "\t}",
        ]
    eff += ["}", "",
            "# Any scope. OUT: timed state flag WA_AI_NAVAL_controller_holds_sea on coastal states whose",
            "# controller (at war) holds naval control of an adjacent sea region.",
            "WA_AI_NAVAL_update_sea_control_states = {"]
    for r, states in shore.items():
        for s in states:
            eff.append(
                f"\t{s} = {{ if = {{ limit = {{ CONTROLLER = {{ has_war = yes has_naval_control = {r} }} }}"
                f" clr_state_flag = WA_AI_NAVAL_controller_holds_sea"
                f" set_state_flag = {{ flag = WA_AI_NAVAL_controller_holds_sea value = 1 days = {FLAG_DAYS} }} }} }}")
    eff.append("}")

    trg += ["# [naval-invasion-discipline] N3 B1 gates, one per sea region: avoid a sea the enemy controls",
            "# while our fair-share posture is inferior. THIS = country.", ""]
    strat += [
        "# [naval-invasion-discipline] N3 B1 - a navy that is outmatched overall does not feed its ships",
        "# into a sea region the enemy already controls. One block per sea region; region ids are the",
        "# engine's own (has_enemy_naval_control), the shore link comes from the map.",
        f"# range:   naval_avoid_region +{AVOID_VALUE} (between a soft nudge and a soft wall)",
        "# policy:  Additive per region",
        "# domain:  NAVAL",
        "",
    ]
    for r in shore:
        trg += [f"WA_AI_NAVAL_should_avoid_lost_sea_{r} = {{",
                "\tWA_AI_NAVAL_is_navally_inferior = yes",
                f"\thas_country_flag = WA_AI_NAVAL_lost_sea_{r}",
                "}"]
        strat += [f"WA_AI_NAVAL_DEFAULT_avoid_lost_sea_{r} = {{",
                  f"\tenable = {{ WA_AI_NAVAL_should_avoid_lost_sea_{r} = yes }}",
                  "\tabort_when_not_enabled = yes",
                  f"\tai_strategy = {{ type = naval_avoid_region id = {r} value = {AVOID_VALUE} }}",
                  "}"]
    return {OUT_EFFECTS: "\n".join(eff) + "\n",
            OUT_TRIGGERS: "\n".join(trg) + "\n",
            OUT_STRATEGY: "\n".join(strat) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    shore, n_regions = build()
    files = render(shore)
    n_links = sum(len(v) for v in shore.values())
    print(f"sea regions {n_regions}, with a shore {len(shore)}, region-state links {n_links}")
    if a.check:
        drift = [p for p, t in files.items()
                 if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != t]
        for p in drift:
            print(f"DRIFT {p.relative_to(REPO)}")
        return 1 if drift else 0
    for p, t in files.items():
        if a.dry_run:
            print(f"would write {p.relative_to(REPO)} ({t.count(chr(10))} lines)")
        else:
            p.write_bytes(t.encode("ascii"))
            print(f"wrote {p.relative_to(REPO)} ({t.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
