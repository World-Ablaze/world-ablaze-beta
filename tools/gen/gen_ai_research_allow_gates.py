#!/usr/bin/env python3
"""
gen_ai_research_allow_gates.py - hard-block a list of technologies for the AI via `allow`.

[research-allow-gate] Down-weighting (`ai_will_do` factor 0, `research_weight_factor = -100`)
does NOT stop the AI from researching a technology: it only reorders a menu that still has a
positive entry, and with a free slot the AI takes a zero-weight tech anyway (campaign
f9321934, see common/ai_strategy/WA_AI_RESEARCH_COUNTRY_USA.txt). The construct that blocks
is an `allow = { ... }` on the technology itself - vanilla uses it the same way
(`jungle_warfare`, "only from focus"). This tool owns those blocks.

Source of truth = BLOCKED_TECHS below. Every listed tech gets one managed `allow` block,
delimited by marker comments, right after its opening line; every managed block whose tech
is no longer listed is removed. Running the tool twice changes nothing (idempotent). The
`ai_will_do` replacer (tools/migrations/ai_will_do/) rewrites only the `ai_will_do` block, so
a managed `allow` survives regeneration.

Refuses (exit 2) when a listed tech is not defined in common/technologies/, or when it
already carries an `allow` block the tool does not own - resolve by hand first (delete it, or
keep it and drop the tech from the list). Bytes outside the managed regions are untouched:
BOM (there is none today, and the tool never adds one), CRLF, indentation, comments.

Usage (any cwd; the mod root is derived from this file's location):
  python gen_ai_research_allow_gates.py --dry-run   # unified diff of what would change
  python gen_ai_research_allow_gates.py             # write the technology files
  python gen_ai_research_allow_gates.py --check     # exit 1 if the files are not in sync
"""

import argparse
import difflib
import re
import sys
from pathlib import Path

# ---------------------------------------------------------------------------------------
# CONFIGURATION - the only part meant to be edited.
# ---------------------------------------------------------------------------------------

# Technologies the AI must never research. Keys as written in common/technologies/*.txt.
BLOCKED_TECHS = [
    "sov_light_spg_tank_1",  # SU-5
    "sov_light_spg_tank_2",  # SU-26
]

# Body of the generated `allow` block, one trigger line per entry (indent added by the tool).
# `NOT = { is_ai = yes }` = hard block for every AI country, humans research normally.
# Replace with a scripted trigger (e.g. `NOT = { WA_AI_RESEARCH_should_block_x = yes }`)
# for a dynamic gate.
GATE_TERMS = [
    "NOT = { is_ai = yes }",
]

# ---------------------------------------------------------------------------------------

REPO = Path(__file__).resolve().parents[2]
TECH_DIR = REPO / "common" / "technologies"

MARK_BEGIN = "# WA_AI_RESEARCH_ALLOW_GATE begin - generated by tools/gen/gen_ai_research_allow_gates.py, do not edit"
MARK_END = "# WA_AI_RESEARCH_ALLOW_GATE end"
RE_TECH_HEADER = re.compile(r"^\t([A-Za-z0-9_]+)\s*=\s*\{")
RE_ALLOW = re.compile(r"^\s*allow\s*=\s*\{")
RE_MARK_BEGIN = re.compile(r"^\s*# WA_AI_RESEARCH_ALLOW_GATE begin\b")
RE_MARK_END = re.compile(r"^\s*# WA_AI_RESEARCH_ALLOW_GATE end\b")


def managed_block(nl):
    """The exact lines the tool owns for one blocked tech (tech body indent = two tabs)."""
    lines = [
        "\t\t" + MARK_BEGIN,
        "\t\t# [research-allow-gate] AI never researches this tech; humans are not affected.",
        "\t\tallow = {",
    ]
    lines += ["\t\t\t" + term for term in GATE_TERMS]
    lines += ["\t\t}", "\t\t" + MARK_END]
    return [line + nl for line in lines]


def brace_delta(line):
    """Net brace count of a line, ignoring everything after a `#` comment marker."""
    code = line.split("#", 1)[0]
    return code.count("{") - code.count("}")


def split_techs(lines):
    """Yield (tech_id, header_index, end_index_exclusive) for every depth-1 tech block.

    Technology files are `technologies = { <tech> = { ... } ... }`; a tech header is a
    one-tab-indented `<id> = {` seen while the brace depth is 1.
    """
    depth = 0
    current = None
    for i, line in enumerate(lines):
        if depth == 1 and current is None:
            m = RE_TECH_HEADER.match(line)
            if m:
                current = (m.group(1), i)
        depth += brace_delta(line)
        if depth < 0:
            raise ValueError(f"brace depth went negative at line {i + 1}")
        if current is not None and depth == 1:
            yield current[0], current[1], i + 1
            current = None
    if depth != 0:
        raise ValueError(f"unbalanced braces (final depth {depth})")


def process_file(path, blocked, report):
    raw = path.read_bytes()
    bom = raw.startswith(b"\xef\xbb\xbf")
    body_bytes = raw[3:] if bom else raw
    text = body_bytes.decode("utf-8", errors="surrogateescape")
    nl = "\r\n" if "\r\n" in text else "\n"
    lines = text.splitlines(keepends=True)

    try:
        techs = list(split_techs(lines))
    except ValueError as exc:
        report["errors"].append(f"{path.name}: {exc}")
        return None

    new_lines = []
    cursor = 0
    for tech_id, start, end in techs:
        new_lines.extend(lines[cursor:start])
        block_lines = lines[start:end]
        header, body = block_lines[0], block_lines[1:]

        # locate the managed region and any foreign `allow` at tech depth
        managed = None
        foreign_allow = False
        depth = 0
        i = 0
        while i < len(body):
            line = body[i]
            if RE_MARK_BEGIN.match(line):
                j = i
                while j < len(body) and not RE_MARK_END.match(body[j]):
                    j += 1
                if j == len(body):
                    report["errors"].append(f"{path.name}: {tech_id}: begin marker without end marker")
                    return None
                managed = (i, j + 1)
                i = j + 1
                continue
            if depth == 0 and RE_ALLOW.match(line):
                foreign_allow = True
            depth += brace_delta(line)
            i += 1

        if tech_id in blocked:
            report["found"].add(tech_id)
            if foreign_allow:
                report["errors"].append(
                    f"{path.name}: {tech_id}: has an `allow` block the tool does not own - resolve by hand"
                )
                return None
            block = managed_block(nl)
            if managed is None:
                body = block + body
                report["changes"].append(f"{path.name}: + {tech_id}")
            elif body[managed[0]:managed[1]] != block:
                body = body[:managed[0]] + block + body[managed[1]:]
                report["changes"].append(f"{path.name}: ~ {tech_id}")
        elif managed is not None:
            body = body[:managed[0]] + body[managed[1]:]
            report["changes"].append(f"{path.name}: - {tech_id}")

        new_lines.append(header)
        new_lines.extend(body)
        cursor = end
    new_lines.extend(lines[cursor:])

    if new_lines == lines:
        return None
    list(split_techs(new_lines))  # the rewritten file must still balance
    out = "".join(new_lines).encode("utf-8", errors="surrogateescape")
    if bom:
        out = b"\xef\xbb\xbf" + out
    return lines, new_lines, out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="print the diff, write nothing")
    ap.add_argument("--check", action="store_true", help="exit 1 if any file would change (writes nothing)")
    args = ap.parse_args()

    dup = {t for t in BLOCKED_TECHS if BLOCKED_TECHS.count(t) > 1}
    if dup:
        print(f"ERROR: duplicated entries in BLOCKED_TECHS: {sorted(dup)}")
        return 2

    blocked = set(BLOCKED_TECHS)
    report = {"found": set(), "changes": [], "errors": []}
    pending = {}
    for path in sorted(TECH_DIR.glob("*.txt")):
        result = process_file(path, blocked, report)
        if result is not None:
            pending[path] = result

    for t in sorted(blocked - report["found"]):
        report["errors"].append(f"{t}: not defined in any file under common/technologies/")
    if report["errors"]:
        for e in report["errors"]:
            print(f"ERROR: {e}")
        return 2

    if not pending:
        print(f"in sync: {len(blocked)} gated tech(s), nothing to change")
        return 0

    for path, (old, new, _) in pending.items():
        rel = path.relative_to(REPO).as_posix()
        sys.stdout.writelines(difflib.unified_diff(old, new, f"a/{rel}", f"b/{rel}"))
    print()
    for c in report["changes"]:
        print(c)

    if args.check:
        print(f"\nOUT OF SYNC: {len(pending)} file(s) would change")
        return 1
    if args.dry_run:
        print(f"\ndry run: {len(pending)} file(s) would change")
        return 0
    for path, (_, _, out) in pending.items():
        path.write_bytes(out)
    print(f"\nwrote {len(pending)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
